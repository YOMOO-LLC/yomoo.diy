// 步骤到AI角色的映射
export const STEP_TO_ROLE: Record<number, string> = {
  1: 'businessAnalyst', // 业务类型分析
  2: 'brandConsultant', // 品牌信息收集
  3: 'serviceExpert', // 服务产品详情
  4: 'designer', // 设计风格确定
  5: 'marketingExpert', // 联系方式和推广
  6: 'projectManager', // 最终确认总结
};

// 获取指定步骤的AI角色
export function getAIRoleForStep(step: number): AIRole {
  const roleId = STEP_TO_ROLE[step];

  if (!roleId || !AI_ROLES[roleId]) {
    throw new Error(`No AI role defined for step ${step}`);
  }

  return AI_ROLES[roleId];
}

// 获取AI角色的完整提示词
export function getSystemPromptForStep(step: number): string {
  const role = getAIRoleForStep(step);
  return role.systemPrompt;
}

// 获取AI角色的初始消息
export function getInitialMessageForStep(step: number): string {
  const role = getAIRoleForStep(step);
  return role.initialMessage;
}
